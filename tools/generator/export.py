"""Write a built profile into the mod folder in the form the Lua side reads.

    mod/textures/NGLA/map/t<px>_<col>_<row>.png    map tile pyramid (empty ocean tiles skipped)
    mod/scripts/NGLA/generated/data.lua         frame, tile list, locations
"""
from __future__ import annotations

import shutil
from pathlib import Path

import numpy as np

from render import DEEP_RGB, draw_roads

TILE = 512
OCEAN_RGB = DEEP_RGB        # open-sea colour from render.py; tiles of only this are skipped


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'


def export_interiors(mod_dir: Path, north: dict, exits: dict, route: dict) -> dict:
    """mod/scripts/NGLA/generated/interiors.lua: per-interior compass data,
    keyed by lowercase cell name."""
    lines = [
        "-- GENERATED by tools/generator/build.py --install. Do not edit.",
        "-- north[cell] = NorthMarker z rotation (radians)",
        "-- exits[cell] = doors leading outdoors: {doorX, doorY, outsideX, outsideY}",
        "-- route[cell] = {doorX, doorY}: door one step closer to the outdoors",
        "return {",
        "  north = {",
    ]
    for name, rz in sorted(north.items(), key=lambda kv: kv[0].lower()):
        if abs(rz) > 1e-4:   # 0 is the default; skip it to keep the file small
            lines.append(f"    [{lua_str(name.lower())}] = {rz:.4f},")
    lines += ["  },", "  exits = {"]
    for c, outs in sorted(exits.items()):
        lines.append(f"    [{lua_str(c)}] = {{" + ", ".join(f"{{{a},{b},{x},{y}}}" for a, b, x, y in outs) + "},")
    lines += ["  },", "  route = {"]
    for c, (x, y) in sorted(route.items()):
        lines.append(f"    [{lua_str(c)}] = {{{x},{y}}},")
    lines += ["  },", "}", ""]
    gen_dir = mod_dir / "scripts" / "NGLA" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "interiors.lua").write_text("\n".join(lines), encoding="utf-8")
    return {"exits": len(exits), "route": len(route)}


LOGICAL_PX = 32            # map-space pixels per cell on the Lua side (zoom levels are tuned to this)
LEVEL_PX = (64, 32, 16, 8)  # tile pyramid: pixels per cell of each level, finest first


def _write_tiles(tex_dir: Path, img, px: int) -> list[tuple[int, int]]:
    from PIL import Image
    a = np.asarray(img)
    cols = -(-img.width // TILE)
    rows = -(-img.height // TILE)
    tiles = []
    for r in range(rows):
        for c in range(cols):
            part = a[r * TILE:(r + 1) * TILE, c * TILE:(c + 1) * TILE]
            if (part == OCEAN_RGB).all():
                continue
            full = np.empty((TILE, TILE, 3), np.uint8)
            full[:] = OCEAN_RGB
            full[:part.shape[0], :part.shape[1]] = part
            Image.fromarray(full).save(tex_dir / f"t{px}_{c}_{r}.png", optimize=True)
            tiles.append((c, r))
    return tiles


def export_gates(mod_dir: Path, rules: list) -> dict:
    """mod/scripts/NGLA/generated/gates.lua: when quest-controlled doors exist."""
    def cond(c):
        return "{" + f"{lua_str(c[0])},{lua_str(c[1])},{lua_str(c[2])},{c[3]}" + "}"

    def rule(r):
        parts = ["c={" + ",".join(cond(c) for c in r["c"]) + "}"]
        if r["v"] is not None:
            parts.append("v=" + ("true" if r["v"] else "false"))
        if r["s"]:
            parts.append("s=true")
        return "{" + ",".join(parts) + "}"

    lines = [
        "-- GENERATED by tools/generator/build.py --install. Do not edit.",
        "-- rules[gate] = ordered list; every rule whose conditions hold sets visibility (v) or stops (s).",
        '-- condition = {kind, name, op, value}; kind "g" = global variable, "j" = journal index',
        "return {",
        "  rules = {",
        *("    {" + ",".join(rule(r) for r in rs) + "}," for rs in rules),
        "  },",
        "}",
        "",
    ]
    gen_dir = mod_dir / "scripts" / "NGLA" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "gates.lua").write_text("\n".join(lines), encoding="utf-8")
    return {"gates": len(rules)}


def export(mod_dir: Path, img, frame, locations, profile: str, content: list[str]) -> dict:
    """img is the map at frame.px pixels per cell (64 for a release build); lower
    levels of the pyramid are averaged down from it."""
    tex_dir = mod_dir / "textures" / "NGLA" / "map"
    if tex_dir.exists():
        shutil.rmtree(tex_dir)
    tex_dir.mkdir(parents=True)

    levels = []
    total = 0
    for px in LEVEL_PX:
        if px > frame.px or frame.px % px:
            continue
        level_img = img if px == frame.px else img.reduce(frame.px // px)
        level_img = draw_roads(level_img, frame)    # roads are drawn per level, so they stay crisp
        tiles = _write_tiles(tex_dir, level_img, px)
        total += len(tiles)
        levels.append((px, tiles))

    scale = LOGICAL_PX / frame.px
    lines = [
        "-- GENERATED by tools/generator/build.py --install. Do not edit.",
        "return {",
        f"  profile = {lua_str(profile)},",
        "  content = {" + ", ".join(lua_str(c) for c in content) + "},",
        f"  minCellX = {frame.min_x}, maxCellY = {frame.max_y}, cols = {frame.cols}, rows = {frame.rows},",
        "  -- map space: pxPerCell pixels per cell; each tile level covers tileSize * pxPerCell / px map pixels",
        f"  pxPerCell = {LOGICAL_PX}, tileSize = {TILE}, "
        f"mapWidth = {round(img.width * scale)}, mapHeight = {round(img.height * scale)},",
        "  oceanColor = {" + ", ".join(f"{v / 255:.3f}" for v in OCEAN_RGB) + "},",
        "  -- tile pyramid, finest first: textures/NGLA/map/t<px>_<col>_<row>.png",
        "  levels = {",
        *(f"    {{px = {px}, tiles = {{" + ", ".join(f"{{{c},{r}}}" for c, r in tiles) + "}},"
          for px, tiles in levels),
        "  },",
        "  -- n=name, x/y=world position, k=kind (e=entrance, l=landmark), t=town interior, s=sub-map space,",
        "  -- a={x,y,z,rotZ}=fast travel landing, ac=interior to land in, ag=settle onto the ground, g=quest gate (see gates.lua)",
        "  locations = {",
    ]
    for l in locations:
        parts = [f"n={lua_str(l.name)}", f"x={round(l.pos[0])}", f"y={round(l.pos[1])}",
                 f"k={lua_str('e' if l.kind == 'entrance' else 'l')}"]
        if l.town_interior:
            parts.append("t=true")
        if l.space:
            parts.append(f"s={lua_str(l.space)}")
        if l.gate is not None:
            parts.append(f"g={l.gate}")
        if l.arrive:
            x, y, z, r = l.arrive
            parts.append(f"a={{{x:.1f},{y:.1f},{z:.1f},{r:.3f}}}")
            if l.arrive_cell:
                parts.append(f"ac={lua_str(l.arrive_cell)}")
            if l.arrive_ground:
                parts.append("ag=true")
        lines.append("    {" + ", ".join(parts) + "},")
    lines += ["  },", "}", ""]

    gen_dir = mod_dir / "scripts" / "NGLA" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "data.lua").write_text("\n".join(lines), encoding="utf-8")
    return {"tiles": total, "levels": [(px, len(t)) for px, t in levels]}
