"""Write a built profile into the mod folder in the form the Lua side reads.

    mod/textures/NGLA/map/t_<col>_<row>.png    map tiles (empty ocean tiles skipped)
    mod/scripts/NGLA/generated/data.lua         frame, tile list, locations
"""
from __future__ import annotations

import shutil
from pathlib import Path

import numpy as np

TILE = 512
OCEAN_RGB = (40, 70, 100)   # deep-water colour from render.py; tiles of only this are skipped


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'


def export_interiors(mod_dir: Path, north: dict, exits: dict, route: dict) -> dict:
    """mod/scripts/NGLA/generated/interiors.lua: per-interior compass data,
    keyed by lowercase cell name."""
    lines = [
        "-- GENERATED by tools/generator/build.py --install. Do not edit.",
        "-- north[cell] = NorthMarker z rotation (radians)",
        "-- exits[cell] = doors leading outdoors: {doorX, doorY, outsideX, outsideY}",
        "-- route[cell] = {doorX, doorY}: door one step closer to the outdoors",
        "return {",
        "  north = {",
    ]
    for name, rz in sorted(north.items(), key=lambda kv: kv[0].lower()):
        if abs(rz) > 1e-4:   # 0 is the default; skip it to keep the file small
            lines.append(f"    [{lua_str(name.lower())}] = {rz:.4f},")
    lines += ["  },", "  exits = {"]
    for c, outs in sorted(exits.items()):
        lines.append(f"    [{lua_str(c)}] = {{" + ", ".join(f"{{{a},{b},{x},{y}}}" for a, b, x, y in outs) + "},")
    lines += ["  },", "  route = {"]
    for c, (x, y) in sorted(route.items()):
        lines.append(f"    [{lua_str(c)}] = {{{x},{y}}},")
    lines += ["  },", "}", ""]
    gen_dir = mod_dir / "scripts" / "NGLA" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "interiors.lua").write_text("\n".join(lines), encoding="utf-8")
    return {"exits": len(exits), "route": len(route)}


def export(mod_dir: Path, img, frame, locations, profile: str, content: list[str]) -> dict:
    tex_dir = mod_dir / "textures" / "NGLA" / "map"
    if tex_dir.exists():
        shutil.rmtree(tex_dir)
    tex_dir.mkdir(parents=True)

    a = np.asarray(img)
    cols = -(-img.width // TILE)
    rows = -(-img.height // TILE)
    tiles = []
    for r in range(rows):
        for c in range(cols):
            part = a[r * TILE:(r + 1) * TILE, c * TILE:(c + 1) * TILE]
            if (part == OCEAN_RGB).all():
                continue
            full = np.empty((TILE, TILE, 3), np.uint8)
            full[:] = OCEAN_RGB
            full[:part.shape[0], :part.shape[1]] = part
            from PIL import Image
            Image.fromarray(full).save(tex_dir / f"t_{c}_{r}.png", optimize=True)
            tiles.append((c, r))

    lines = [
        "-- GENERATED by tools/generator/build.py --install. Do not edit.",
        "return {",
        f"  profile = {lua_str(profile)},",
        "  content = {" + ", ".join(lua_str(c) for c in content) + "},",
        f"  minCellX = {frame.min_x}, maxCellY = {frame.max_y}, cols = {frame.cols}, rows = {frame.rows},",
        f"  pxPerCell = {frame.px}, tileSize = {TILE}, mapWidth = {img.width}, mapHeight = {img.height},",
        "  oceanColor = {" + ", ".join(f"{v / 255:.3f}" for v in OCEAN_RGB) + "},",
        "  tiles = {" + ", ".join(f"{{{c},{r}}}" for c, r in tiles) + "},",
        "  -- n=name, x/y=world position, k=kind (e=entrance, l=landmark), t=town interior, s=sub-map space",
        "  locations = {",
    ]
    for l in locations:
        parts = [f"n={lua_str(l.name)}", f"x={round(l.pos[0])}", f"y={round(l.pos[1])}",
                 f"k={lua_str('e' if l.kind == 'entrance' else 'l')}"]
        if l.town_interior:
            parts.append("t=true")
        if l.space:
            parts.append(f"s={lua_str(l.space)}")
        lines.append("    {" + ", ".join(parts) + "},")
    lines += ["  },", "}", ""]

    gen_dir = mod_dir / "scripts" / "NGLA" / "generated"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "data.lua").write_text("\n".join(lines), encoding="utf-8")
    return {"tiles": len(tiles), "of": cols * rows}
